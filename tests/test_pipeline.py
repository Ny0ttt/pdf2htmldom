def test_rows_attach_a_dot_above_short_letters():
    """The dot of the i in "in" sits above the letters and overlaps none of
    them vertically; it must stay on the row, not become a row of its own."""
    import numpy as np

    from pdf2htmldom.glyphs import _rows

    def rect(x0, y0, x1, y1):
        return np.array([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], float)

    letters = [rect(0, 4, 1, 9), rect(2, 4, 6, 9), rect(7, 4, 11, 9), rect(12, 4, 16, 9), rect(17, 4, 21, 9)]
    dot = rect(0, 2.5, 1, 3.5)
    rows = _rows(letters + [dot])
    assert len(rows) == 1 and len(rows[0]) == 6


