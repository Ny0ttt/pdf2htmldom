from pdf2htmldom.boxes import detect_frames  # noqa: E402


def _frame_rules(x0, y0, x1, y1, t=_T, top=True, color="#000000"):
    out = [
        _v(x0, y0, y1, 0, color=color),
        _v(x1, y0, y1, 1, color=color),
        _h(x0, x1 + t, y1 - t / 2, 2, color=color),
    ]
    if top:
        out.append(_h(x0, x1 + t, y0, 3, color=color))
    return out


def test_four_rules_become_one_frame():
    frames, kept, absorbed = detect_frames(_frame_rules(34, 106.9, 575.7, 123.7), 1)
    assert len(frames) == 1 and frames[0].top
    assert kept == [] and absorbed == 4


def test_open_top_becomes_bracket():
    frames, kept, _ = detect_frames(_frame_rules(202, 743, 342, 757, top=False), 1)
    assert len(frames) == 1 and not frames[0].top and kept == []


def test_misaligned_bottom_is_not_a_frame():
    rules = _frame_rules(34, 100, 300, 200)
    rules[2] = _h(34, 250, 200, 2)  # bottom stops 50pt short of the right side
    frames, kept, _ = detect_frames(rules, 1)
    assert frames == [] and len(kept) == 4


