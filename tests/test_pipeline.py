def test_doctor_reports_every_dependency():
    from pdf2htmldom.doctor import report, run_checks

    checks = run_checks()
    names = {c.name for c in checks}
    for expected in ("python", "pymupdf", "playwright", "chromium", "tesseract", "font: Arial"):
        assert expected in names, expected
    assert all(c.status in ("ok", "warn", "fail") for c in checks)
    # The suite itself needs Chromium, so on any machine that runs it, doctor must agree.
    assert next(c for c in checks if c.name == "chromium").status == "ok"
    assert report(checks).splitlines()[-1].startswith(("Ready", "0 problem"))


def test_doctor_exit_code_is_failure_only_on_fail(monkeypatch, capsys):
    from pdf2htmldom import cli, doctor

    monkeypatch.setattr(doctor, "run_checks", lambda: [doctor.Check("x", "warn", "degraded")])
    assert cli.main(["doctor"]) == 0
    monkeypatch.setattr(doctor, "run_checks", lambda: [doctor.Check("x", "fail", "broken", "do y")])
    assert cli.main(["doctor"]) == 1
    assert "fix: do y" in capsys.readouterr().out
